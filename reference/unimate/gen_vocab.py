"""Writes model3d/unimate/src/vocab.rs from UniMate's data_process/joint_annotation/vocab.py by parsing its source with
`ast` (the file is read as text; nothing of it runs): the name-cleaning vocabulary the rule-based cleaner (names.rs) uses.

    python3 gen_vocab.py REPO/data_process/joint_annotation/vocab.py > model3d/unimate/src/vocab.rs
"""
import ast
import sys

WANT_DICTS = ["MIXAMO_MAP", "JAPANESE_WORDS", "CANONICAL", "STANDALONE_MAP", "SIDE_WORDS", "FOREIGN_PARTS"]
WANT_LISTS = ["REMOVE_PREFIXES", "QUALIFIERS"]


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    tree = ast.parse(open(sys.argv[1], encoding="utf-8").read())
    vals = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            n = node.targets[0].id
            if n in WANT_DICTS or n in WANT_LISTS:
                vals[n] = ast.literal_eval(node.value)
    print("//! The name-cleaning vocabulary of UniMate's data_process/joint_annotation/vocab.py (MIT), as tables:")
    print("//! generated by reference/unimate/gen_vocab.py (it parses that file's source, nothing of it runs).")
    print()
    for n in WANT_DICTS:
        print(f"pub const {n}: &[(&str, &str)] = &[")
        for k, v in vals[n].items():
            print(f"    ({rs(k)}, {rs(v)}),")
        print("];\n")
    for n in WANT_LISTS:
        print(f"pub const {n}: &[&str] = &[")
        for k in vals[n]:
            print(f"    {rs(k)},")
        print("];\n")


main()
